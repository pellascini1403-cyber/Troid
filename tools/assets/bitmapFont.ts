/** Accents and the few typographic marks the labels may carry, as the plain letter or mark the font has. */
const FOLD: Record<string, string> = { Á: 'A', É: 'E', Í: 'I', Ó: 'O', Ú: 'U', Ü: 'U', Ñ: 'N', '×': 'X', '→': '>', '·': '-', '—': '-', '–': '-', '≤': '<', '≥': '>', '°': "'", '“': "'", '”': "'", '’': "'", '«': "'", '»': "'", '¿': '?', '¡': '!' };

const glyph = (ch: string): readonly string[] => {
  const up = ch.toUpperCase();
  return G[up] ?? G[FOLD[up] ?? ''] ?? G['?']!;
};

/** The width in pixels of `text` at `scale`: each glyph is 5 wide with one column between. */
export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * (FONT_W + 1) - 1) * scale;
}

export type Rgba = readonly [number, number, number, number];

/** Draws `text` with its top-left at (x, y); pixels outside the image are skipped. Returns the width drawn. */
export function drawText(img: RgbaImage, text: string, x: number, y: number, color: Rgba, scale = 1): number {
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    for (let row = 0; row < FONT_H; row++) {
      for (let col = 0; col < FONT_W; col++) {
        if (g[row]![col] !== '1') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            const px = cx + col * scale + sx;
            const py = y + row * scale + sy;
            if (px < 0 || py < 0 || px >= img.width || py >= img.height) continue;
            const o = (py * img.width + px) * 4;
            img.data[o] = color[0];
            img.data[o + 1] = color[1];
            img.data[o + 2] = color[2];
            img.data[o + 3] = color[3];
          }
        }
      }
    }
    cx += (FONT_W + 1) * scale;
  }
  return cx - x - scale;
}
